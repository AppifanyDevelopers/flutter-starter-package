  @override
  Future<Either<AppError, List<FaqItem>>> getFaqs({
    int page = 1,
    int pageSize = 10,
    String? query,
  }) async {
    await Future<void>.delayed(const Duration(milliseconds: 500));

    final normalizedQuery = query?.trim().toLowerCase();
    final matches = normalizedQuery == null || normalizedQuery.isEmpty
        ? _allFaqs
        : _allFaqs
            .where(
              (faq) =>
                  faq.question.toLowerCase().contains(normalizedQuery) ||
                  faq.answer.toLowerCase().contains(normalizedQuery),
            )
            .toList();

    final start = (page - 1) * pageSize;
    if (start >= matches.length) return right(const []);
    final end = (start + pageSize).clamp(0, matches.length);
    return right(matches.sublist(start, end));
  }

